#!/usr/bin/env bash
# Wizard: Create Profile

# ============================================================================
# WIZARD: Create Profile
# ============================================================================
_wizard_create_profile() {
  _wiz_step "Create New Profile"
  
  local name description default_branch keep_images services_timeout
  local retry_enabled retry_max retry_delay retry_max_delay
  
  # Basic info
  _wiz_prompt "Profile name (e.g. server-prod)" "" name
  [ -z "$name" ] && { _wiz_error "Profile name is required"; return 1; }

  if [[ ! "$name" =~ ^[a-zA-Z0-9][a-zA-Z0-9_-]*$ ]]; then
    _wiz_error "Invalid profile name: '$name' (only alphanumeric, hyphens and underscores allowed, must start with letter or digit)"
    return 1
  fi
  
  # Check if exists
  local profile_dir="$PLATFORM_ROOT/profiles/$name"
  if [ -d "$profile_dir" ]; then
    if ! _wiz_confirm "Profile '$name' already exists. Overwrite?" "n"; then
      echo "  Cancelled."
      return 1
    fi
  fi
  
  _wiz_prompt "Description" "$name server configuration" description
  
  echo ""
  echo "  $(_wiz_bold "Git settings:")"
  _wiz_prompt "Default branch" "develop" default_branch
  
  echo ""
  echo "  $(_wiz_bold "Swarm settings:")"
  _wiz_prompt "Services ready timeout (seconds)" "30" services_timeout
  _wiz_prompt "Keep images count (for prune)" "3" keep_images
  
  echo ""
  echo "  $(_wiz_bold "Retry settings:")"
  if _wiz_confirm "Enable retry for network operations?" "y"; then
    retry_enabled="true"
    _wiz_prompt "Max retry attempts" "3" retry_max
    _wiz_prompt "Initial delay (seconds)" "2" retry_delay
    _wiz_prompt "Max delay (seconds)" "30" retry_max_delay
  else
    retry_enabled="false"
    retry_max="3"
    retry_delay="2"
    retry_max_delay="30"
  fi
  
  # Create profile directory structure
  mkdir -p "$profile_dir/stacks"
  mkdir -p "$profile_dir/scripts"
  
  # Generate config.yaml
  cat > "$profile_dir/config.yaml" <<EOF
# Profile: $name
# Generated by swarmcli create wizard

name: $name
description: $description

# Docker Swarm settings
swarm:
  # Timeout for services to become ready after deploy (seconds)
  services_ready_timeout: $services_timeout
  
  # Number of image versions to keep locally after prune
  # Recommended: 3 (current + previous + one backup for rollback)
  # Without Container Registry, old images cannot be restored
  keep_images_count: $keep_images

# Git settings
git:
  # Default branch for repositories
  default_branch: $default_branch
  
  # Git authentication (use environment variables)
  # http_token: \${GIT_HTTP_TOKEN}
  # ssh_key: \${GIT_SSH_KEY}

# Retry logic for network operations (git clone, docker pull, etc.)
retry:
  enabled: $retry_enabled
  max_attempts: $retry_max
  initial_delay: $retry_delay
  max_delay: $retry_max_delay
EOF

  # Generate globals.yaml template
  cat > "$profile_dir/stacks/globals.yaml" <<'EOF'
# Global variables for all stacks in this profile
# These are loaded before stack-specific variables
#
# Usage in docker-stack.yml: ${VAR_NAME}
# Usage in variables.yaml: can reference with ${VAR_NAME}
#
# Example:
#   TZ: Europe/Moscow
#   LOG_LEVEL: info
#   DOMAIN: example.com

TZ: Europe/Moscow
LOG_LEVEL: info
EOF

  # Generate resources.yaml template
  cat > "$profile_dir/stacks/resources.yaml" <<'EOF'
# Resource limits and reservations for services
# These are automatically injected into docker-stack.yml during deploy
#
# Format:
#   <stack_name>:
#     <service_name>:
#       limits:
#         cpus: "0.5"
#         memory: 512M
#       reservations:
#         cpus: "0.25"
#         memory: 256M
#
# Example:
#   my-stack:
#     api:
#       limits:
#         cpus: "1.0"
#         memory: 1G
#       reservations:
#         cpus: "0.5"
#         memory: 512M
#     worker:
#       limits:
#         memory: 2G

# Add your resource definitions here:
EOF

  # Generate endpoints.yaml template
  cat > "$profile_dir/stacks/endpoints.yaml" <<'EOF'
# Service endpoints registry
# Define internal service URLs for cross-stack communication
#
# Usage in variables.yaml:
#   deploy:
#     API_URL: ${SERVICE_CORE_BACKEND}
#
# Format:
#   SERVICE_<NAME>: <url>
#
# Example:
#   SERVICE_CORE_BACKEND: http://core-backend_api:8000
#   SERVICE_FILE_UPLOADER: http://core-file-uploader_app:3000
#   SERVICE_REDIS: redis://shared_redis:6379

# Add your service endpoints here:
EOF

  _wiz_success "Profile created: $profile_dir"
  echo ""
  echo "  Files created:"
  echo "    • config.yaml (profile configuration)"
  echo "    • stacks/globals.yaml (global variables)"
  echo "    • stacks/resources.yaml (resource limits)"
  echo "    • stacks/endpoints.yaml (service endpoints)"
  echo ""
  echo "  Next: run '$(_wiz_cyan "swarmcli create")' to add a stack"
  
  return 0
}
